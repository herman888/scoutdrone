class TestInvoiceCreateValidators:
    """Test InvoiceCreate schema validators."""

    def test_valid_invoice_create(self):
        """Test creating valid invoice."""
        # Act
        invoice = InvoiceCreate(
            invoice_number="INV-001",
            amount=Decimal('1000.00'),
            description="Test invoice",
            issue_date=datetime.now(),
            due_date=datetime.now()
        )
        
        # Assert
        assert invoice.invoice_number == "INV-001"
        assert invoice.amount == Decimal('1000.00')

    def test_invoice_number_optional(self):
        """Test invoice_number is optional (auto-generated if not provided)."""
        # Act - Create invoice without invoice_number
        invoice = InvoiceCreate(
            amount=Decimal('1000.00'),
            description="Test",
            issue_date=datetime.now(),
            due_date=datetime.now()
        )
        
        # Assert - invoice_number should be None (will be auto-generated by service)
        assert invoice.invoice_number is None

    def test_amount_required(self):
        """Test amount is required."""
        # Act & Assert
        with pytest.raises(ValidationError) as exc_info:
            InvoiceCreate(
                invoice_number="INV-001",
                description="Test",
                issue_date=datetime.now(),
                due_date=datetime.now()
            )
        
        assert "amount" in str(exc_info.value).lower()

