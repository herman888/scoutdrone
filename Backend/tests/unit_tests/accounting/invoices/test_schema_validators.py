    def test_dates_required(self):
        """Test issue_date and due_date are required."""
        # Act & Assert
        with pytest.raises(ValidationError) as exc_info:
            InvoiceCreate(
                invoice_number="INV-001",
                amount=Decimal('1000.00'),
                description="Test"
            )
        
        errors = str(exc_info.value).lower()
